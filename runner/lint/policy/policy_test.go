// Only a file with the build cache's extension-less name, cgo's exact header,
// and cgo's //line directive right after it maps to an original.
func TestSourceNameMapsOnlyCgoRewrites(t *testing.T) {
	const header = "// Code generated by cmd/cgo; DO NOT EDIT.\n\n"
	for _, tc := range []struct {
		name string
		file string
		src  string
		want string
	}{
		{"a rewrite with only cgo's two comments", "/cache/ab/abcd-d", header + "//line /src/demo.go:1:1\npackage demo\n", "/src/demo.go"},
		{"a rewrite with more comments after them", "/cache/ab/abcd-d", header + "//line /src/demo.go:1:1\npackage demo\n\n// Later.\nvar x int\n", "/src/demo.go"},
		{"cgo's header without a directive", "/cache/ab/abcd-d", header + "package demo\n", "/cache/ab/abcd-d"},
		{"a directive cgo would not write", "/cache/ab/abcd-d", header + "//line /src/demo.go:7:1\npackage demo\n", "/cache/ab/abcd-d"},
		{"an original that is not Go", "/cache/ab/abcd-d", header + "//line /src/demo.tmpl:1:1\npackage demo\n", "/cache/ab/abcd-d"},
		{"a package file that copies cgo's header", "/src/copy.go", header + "//line /src/demo.go:1:1\npackage demo\n", "/src/copy.go"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fset := token.NewFileSet()
			file, err := parser.ParseFile(fset, tc.file, tc.src, parser.ParseComments|parser.SkipObjectResolution)
			if err != nil {
				t.Fatal(err)
			}

			if got := SourceName(fset, file); got != tc.want {
				t.Errorf("SourceName = %q, want %q", got, tc.want)
			}
		})
	}
}

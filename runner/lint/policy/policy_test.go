// A driver that predates Pass.ReadFile leaves it nil; LV1005 then reads the
// file itself rather than failing.
func TestFormattingReadsTheFileWithoutPassReadFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "messy.go")
	if err := os.WriteFile(path, []byte("package messy\nvar  x = 1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}

	var reported []analysis.Diagnostic
	pass := &analysis.Pass{Analyzer: Formatting, Fset: fset, Files: []*ast.File{file}, Report: func(d analysis.Diagnostic) { reported = append(reported, d) }}
	if _, err := Formatting.Run(pass); err != nil {
		t.Fatal(err)
	}
	if len(reported) != 1 {
		t.Fatalf("an unformatted file read without Pass.ReadFile gave %d diagnostics, want 1", len(reported))
	}
}

// Files the build leaves out, for another platform or behind a build tag, are
// not type-checked but are still Go files gofmt would check, so LV1005 reports
// them too. Staticcheck's runner leaves Pass.IgnoredFiles empty, so LV1005
// finds them in the package directory itself; a driver may list them instead.
func TestFormattingChecksIgnoredFiles(t *testing.T) {
	dir := t.TempDir()
	sources := map[string]string{
		"app.go":               "package app\n",
		"app_test.go":          "package app\n",
		"app_plan9.go":         "package app\nvar  z = 1\n",
		"integration.go":       "//go:build integration\n\npackage app\nvar  y = 1\n",
		"integration_test.go":  "//go:build integration\n\npackage app\nvar  w = 1\n",
		"tools.go":             "//go:build ignore\n\npackage main\nvar  x = 1\n",
		"formatted_ignored.go": "//go:build ignore\n\npackage app\n",
		"generated_ignored.go": "// Code generated by fixture. DO NOT EDIT.\n\n//go:build ignore\n\npackage app\nvar  g = 1\n",
	}
	for name, source := range sources {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	ignored := []string{"app_plan9.go", "formatted_ignored.go", "generated_ignored.go", "integration.go", "integration_test.go", "tools.go"}
	for i, name := range ignored {
		ignored[i] = filepath.Join(dir, name)
	}
	unformatted := []string{"app_plan9.go", "integration.go", "integration_test.go", "tools.go"}

	for _, test := range []struct {
		name    string
		files   []string
		ignored []string
		want    []string
	}{
		{"Staticcheck's runner", []string{"app.go"}, nil, unformatted},
		{"a driver that lists them", []string{"app.go"}, ignored, unformatted},
		// The build with tests sees the same directory; the plain build reports it.
		{"the build with tests", []string{"app.go", "app_test.go"}, nil, nil},
	} {
		fset := token.NewFileSet()
		var files []*ast.File
		for _, name := range test.files {
			file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			files = append(files, file)
		}

		// A driver that lists ignored files permits reading only the package's own.
		var read func(string) ([]byte, error)
		if test.ignored != nil {
			read = func(name string) ([]byte, error) {
				if !slices.Contains(test.ignored, name) && !slices.ContainsFunc(test.files, func(file string) bool { return filepath.Join(dir, file) == name }) {
					return nil, fmt.Errorf("%s is not a file of the package", name)
				}
				return os.ReadFile(name)
			}
		}

		var reported []string
		pass := &analysis.Pass{
			Analyzer:     Formatting,
			Fset:         fset,
			Files:        files,
			IgnoredFiles: test.ignored,
			ReadFile:     read,
			Report: func(d analysis.Diagnostic) {
				position := fset.Position(d.Pos)
				reported = append(reported, fmt.Sprintf("%s:%d", filepath.Base(position.Filename), position.Line))
			},
		}
		if _, err := Formatting.Run(pass); err != nil {
			t.Fatalf("%s: %v", test.name, err)
		}

		var want []string
		for _, name := range test.want {
			want = append(want, name+":1")
		}
		slices.Sort(reported)
		if !slices.Equal(reported, want) {
			t.Errorf("%s reported %v, want %v", test.name, reported, want)
		}
	}
}


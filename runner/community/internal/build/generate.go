package build

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path/filepath"
	"strconv"
)

// exports is what a module's lvrules package declares at the top level. The
// types are left to the compiler, which reports a mismatch against
// community.Module in the generated main.
type exports struct {
	Namespace bool
	// NamespaceValue is Namespace's value when it is a string constant
	// written as a literal, so a mismatch fails before the build.
	NamespaceValue string
	Analyzers      bool
	Renamed        bool
}

// inspect reads the exports of a module's lvrules package from the files the
// go command would compile, so build constraints are honored.
func inspect(ctx context.Context, g goCommand, m Module) (exports, error) {
	pkg := m.Path + "/lvrules"
	output, err := g.run(ctx, "list", "-json", pkg)
	if err != nil {
		return exports{}, fmt.Errorf("%s: listing %s: %s", m.source(), pkg, output.combined())
	}
	var listed struct {
		Dir     string   `json:"Dir"`
		GoFiles []string `json:"GoFiles"`
	}
	if err := json.Unmarshal(output.Stdout, &listed); err != nil {
		return exports{}, fmt.Errorf("%s: reading go list output: %w", m.source(), err)
	}

	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range listed.GoFiles {
		file, err := parser.ParseFile(fset, filepath.Join(listed.Dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return exports{}, fmt.Errorf("%s: %w", m.source(), err)
		}
		files = append(files, file)
	}

	found := declared(files)
	switch {
	case !found.Namespace:
		return exports{}, fmt.Errorf("%s: %s does not declare Namespace", m.source(), pkg)
	case !found.Analyzers:
		return exports{}, fmt.Errorf("%s: %s does not declare Analyzers", m.source(), pkg)
	case found.NamespaceValue != "" && found.NamespaceValue != m.Namespace:
		return exports{}, fmt.Errorf("levenshtein.json declares namespace %q for %s, but its lvrules.Namespace is %q", m.Namespace, m.source(), found.NamespaceValue)
	}
	return found, nil
}

// declared finds the contract's names among a package's top-level
// declarations.
func declared(files []*ast.File) exports {
	var found exports
	for _, file := range files {
		for _, decl := range file.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv == nil && decl.Name.Name == "Analyzers" {
					found.Analyzers = true
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					value, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}
					for i, name := range value.Names {
						//lint:ignore LV1001 these are identifiers read from source, not a finite choice of values.
						switch name.Name {
						case "Namespace":
							found.Namespace = true
							found.NamespaceValue = literal(decl.Tok, value, i)
						case "Renamed":
							found.Renamed = true
						}
					}
				}
			}
		}
	}
	return found
}

// literal is the value of a constant written as a plain string literal, or ""
// for anything else.
func literal(tok token.Token, spec *ast.ValueSpec, i int) string {
	if tok != token.CONST || i >= len(spec.Values) {
		return ""
	}
	lit, ok := spec.Values[i].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return ""
	}
	value, err := strconv.Unquote(lit.Value)
	if err != nil {
		return ""
	}
	return value
}

// generate writes the linter's main package. Each module is imported under a
// positional alias, so module paths never need to be valid identifiers.
func generate(modules []Module, found []exports) ([]byte, error) {
	var text bytes.Buffer
	text.WriteString("// Code generated by levenshtein from levenshtein.json; DO NOT EDIT.\n\n")
	text.WriteString("// Levenshtein-community-lint runs the community lint rules a configuration pins.\npackage main\n\nimport (\n")
	fmt.Fprintf(&text, "\t%q\n\n", communityModule)
	for i, m := range modules {
		fmt.Fprintf(&text, "\tm%d %q\n", i, m.Path+"/lvrules")
	}
	text.WriteString(")\n\nfunc main() {\n\tcommunity.Main([]community.Module{\n")
	for i, m := range modules {
		renamed := "nil"
		if found[i].Renamed {
			renamed = fmt.Sprintf("m%d.Renamed", i)
		}
		fmt.Fprintf(&text, "\t\t{Path: %q, Version: %q, Namespace: m%d.Namespace, Renamed: %s, Analyzers: m%d.Analyzers()},\n", m.Path, m.Version, i, renamed, i)
	}
	text.WriteString("\t})\n}\n")
	return format.Source(text.Bytes())
}

func TestRequestsMustPinExactVersions(t *testing.T) {
	valid := Request{Go: "1.27.1", Staticcheck: "v0.8.1", Community: "/community"}
	for _, test := range []struct {
		name    string
		module  Module
		message string
	}{
		{"branch", Module{Path: "example.com/m", Version: "main"}, "invalid"},
		{"latest", Module{Path: "example.com/m", Version: "latest"}, "invalid"},
		{"short version", Module{Path: "example.com/m", Version: "v1.4"}, "not an exact version"},
		{"major version mismatch", Module{Path: "example.com/m/v2", Version: "v1.0.0"}, "invalid"},
		{"relative replacement", Module{Path: "example.com/m", Version: "v1.0.0", Dir: "../m"}, "must be absolute"},
		{"Staticcheck itself", Module{Path: staticcheckModule, Version: "v0.8.1"}, "cannot be a rule module"},
	} {
		t.Run(test.name, func(t *testing.T) {
			req := valid
			req.Modules = []Module{test.module}

			err := req.validate()

			if err == nil || !strings.Contains(err.Error(), test.message) {
				t.Errorf("got %v, want an error containing %q", err, test.message)
			}
		})
	}

	valid.Modules = []Module{{Path: "example.com/m", Version: "v0.0.0-20260101000000-abcdefabcdef"}, {Path: "example.com/n/v2", Version: "v2.1.0"}}
	if err := valid.validate(); err != nil {
		t.Errorf("a pseudo-version and a /v2 tag are exact pins: %v", err)
	}
}

func parse(t *testing.T, source string) []*ast.File {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "lvrules.go", source, parser.SkipObjectResolution)
	if err != nil {
		t.Fatal(err)
	}
	return []*ast.File{file}
}

func TestDeclaredFindsTheContract(t *testing.T) {
	full := parse(t, `package lvrules
const Namespace = "errs"
var Renamed = map[string]string{"panics": "nopanic"}
func Analyzers() []*analysis.Analyzer { return nil }
func (x T) Namespace() {}
`)
	computed := parse(t, `package lvrules
const prefix = "er"
const Namespace = prefix + "rs"
func Analyzers() []*analysis.Analyzer { return nil }
`)

	if got := declared(full); got != (exports{Namespace: true, NamespaceValue: "errs", Analyzers: true, Renamed: true}) {
		t.Errorf("declared(full) = %+v", got)
	}
	if got := declared(computed); got != (exports{Namespace: true, Analyzers: true}) {
		t.Errorf("a computed Namespace is left to the runtime check: %+v", got)
	}
}

func TestGenerateAliasesEveryModule(t *testing.T) {
	modules := []Module{{Path: "example.com/lvrules-errors", Version: "v1.4.0"}, {Path: "example.com/lvrules-sql", Version: "v0.2.0"}}

	source, err := generate(modules, []exports{{Renamed: true}, {}})
	if err != nil {
		t.Fatal(err)
	}

	text := string(source)
	for _, want := range []string{
		"// Code generated by levenshtein from levenshtein.json; DO NOT EDIT.",
		`m0 "example.com/lvrules-errors/lvrules"`,
		`{Path: "example.com/lvrules-errors", Version: "v1.4.0", Namespace: m0.Namespace, Renamed: m0.Renamed, Analyzers: m0.Analyzers()}`,
		`{Path: "example.com/lvrules-sql", Version: "v0.2.0", Namespace: m1.Namespace, Renamed: nil, Analyzers: m1.Analyzers()}`,
	} {
		if !strings.Contains(text, want) {
			t.Errorf("generated main lacks %q:\n%s", want, text)
		}
	}
}

// The community linter and the core linter must run the same Staticcheck, so
// selection and //lint:ignore behave the same in both. The build refuses any
// other resolution; this catches a bump made in one place only.
func TestStaticcheckIsPinnedOnceForBothLinters(t *testing.T) {
	pinned := pinnedRequest(t).Staticcheck
	for _, manifest := range []string{filepath.Join("..", "..", "go.mod"), filepath.Join("..", "..", "..", "lint", "go.mod")} {
		data, err := os.ReadFile(manifest)
		if err != nil {
			t.Fatal(err)
		}
		file, err := modfile.ParseLax(manifest, data, nil)
		if err != nil {
			t.Fatal(err)
		}

		index := slices.IndexFunc(file.Require, func(require *modfile.Require) bool { return require.Mod.Path == staticcheckModule })
		if index < 0 || file.Require[index].Mod.Version != pinned {
			t.Errorf("%s must require %s %s, as runner/toolchain.json pins", manifest, staticcheckModule, pinned)
		}
	}
}

// Tidy on a toolchain newer than the pin raises the go line instead of
// failing; the build must refuse that as the pinned toolchain would.
func TestARaisedGoLineFailsTheBuild(t *testing.T) {
	for _, test := range []struct {
		manifest string
		message  string
	}{
		{"module m\n\ngo 1.27.1\n", ""},
		{"module m\n\ngo 1.28.0\n", "raised the go line to go 1.28.0"},
		{"module m\n", "raised the go line to no go line"},
	} {
		work := t.TempDir()
		if err := os.WriteFile(filepath.Join(work, "go.mod"), []byte(test.manifest), 0o600); err != nil {
			t.Fatal(err)
		}

		err := checkGoLine(work, "1.27.1")

		if (test.message == "" && err != nil) || (test.message != "" && (err == nil || !strings.Contains(err.Error(), test.message))) {
			t.Errorf("%q: got %v, want %q", test.manifest, err, test.message)
		}
	}
}

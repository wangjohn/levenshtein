func TestChainNamesTheShortestRequirementPath(t *testing.T) {
	graph := strings.Join([]string{
		"levenshtein.local/communitylint example.com/lvrules-errors@v1.5.0",
		"levenshtein.local/communitylint honnef.co/go/tools@v0.8.1",
		"example.com/lvrules-errors@v1.5.0 example.com/helper@v0.3.0",
		"example.com/lvrules-errors@v1.5.0 example.com/other@v1.0.0",
		"example.com/other@v1.0.0 example.com/deeper@v1.0.0",
		"example.com/deeper@v1.0.0 honnef.co/go/tools@v0.9.0",
		"example.com/helper@v0.3.0 honnef.co/go/tools@v0.9.0",
	}, "\n")

	got := Chain(graph, generatedModule, "honnef.co/go/tools@v0.9.0")

	want := []string{"example.com/lvrules-errors@v1.5.0", "example.com/helper@v0.3.0"}
	if !slices.Equal(got, want) {
		t.Errorf("Chain = %v, want %v", got, want)
	}
	if Chain(graph, generatedModule, "honnef.co/go/tools@v1.0.0") != nil {
		t.Error("an unreachable target must give no chain")
	}
}

